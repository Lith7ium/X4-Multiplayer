def capability(snapshot_sha256):
    if snapshot_sha256 != SNAPSHOT_SHA256:
        raise ValueError('Euler import: unreviewed snapshot')
    return {'mode': MODE, 'descriptor_sha256': DESCRIPTOR_SHA256,
            'inputs_sha256': INPUTS_SHA256,
            'movement_records': {'navigation': NAVIGATION_COUNT, 'player': PLAYER_COUNT},
            'banks': {role: {
                'navigation': {'euler': NAVIGATION_EULER, 'absent': ABSENT_PER_BANK, 'quaternion': 0},
                'player': {'euler': PLAYER_EULER, 'absent': 0, 'quaternion': 0}} for role in ROLES}}


def version(mode):
    if mode == v1.MODE:
        return v1
    if mode == MODE:
        import sys
        return sys.modules[__name__]
    raise ValueError('Euler import: unsupported mode')


def validate(value, snapshot_sha256):
    selected = version(value.get('mode') if isinstance(value, dict) else None)
    if canonical(value) != canonical(selected.capability(snapshot_sha256)):
        raise ValueError('Euler import: unreviewed capability or counts')


def header(contract):
    from native_portable import validate_contract
    if not isinstance(contract, dict) or 'import_math' not in contract:
        raise ValueError('Euler import: capability-bearing contract required')
    digest = validate_contract(contract)
    if contract['import_math']['mode'] == v1.MODE:
        return v1.header(contract)
    strings = {'MODE': MODE, 'DESCRIPTOR_SHA256': DESCRIPTOR_SHA256,
               'SNAPSHOT_SHA256': SNAPSHOT_SHA256, 'CONTRACT_SHA256': digest,
               'INPUTS_SHA256': INPUTS_SHA256}
    counts = {'VERSION': 2, 'NAVIGATION_COUNT': NAVIGATION_COUNT, 'PLAYER_COUNT': PLAYER_COUNT,
              'AGENT_COUNT': AGENT_COUNT, 'NAVIGATION_EULER': NAVIGATION_EULER,
              'PLAYER_EULER': PLAYER_EULER, 'NAVIGATION_ABSENT': ABSENT_PER_BANK,
              'PLAYER_ABSENT': 0, 'EULER_PER_BANK': EULER_PER_BANK,
              'ABSENT_PER_BANK': ABSENT_PER_BANK}
    return ('/* Explicit opt-in capability. Generated by portable_import_capability.py. */\n'
            '#ifndef X4_PORTABLE_IMPORT_CAPABILITY_H\n#define X4_PORTABLE_IMPORT_CAPABILITY_H\n'
            + ''.join(f'#define X4ROT_IMPORT_{name} "{value}"\n' for name, value in strings.items())
            + ''.join(f'#define X4ROT_IMPORT_{name} {value}u\n' for name, value in counts.items())
            + '#endif\n')
