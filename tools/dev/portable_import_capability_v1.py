def canonical(value):
    return json.dumps(value, sort_keys=True, separators=(',', ':'), ensure_ascii=True).encode('ascii')


DESCRIPTOR_SHA256 = hashlib.sha256(canonical(DESCRIPTOR)).hexdigest()


def capability(snapshot_sha256):
    if snapshot_sha256 != SNAPSHOT_SHA256:
        raise ValueError('Euler import: unreviewed snapshot')
    return {'mode': MODE, 'descriptor_sha256': DESCRIPTOR_SHA256,
            'navigation_records': NAVIGATION_COUNT,
            'banks': {role: {'euler': EULER_PER_BANK, 'absent': ABSENT_PER_BANK} for role in ROLES}}


def validate(value, snapshot_sha256):
    # Canonical bytes also distinguish bool/int and reject unknown fields.
    if canonical(value) != canonical(capability(snapshot_sha256)):
        raise ValueError('Euler import: unreviewed capability or counts')


def verify_sources(directory):
    for name, expected in SOURCE_SHA256.items():
        data = (directory / name).read_bytes().replace(b'\r\n', b'\n')
        if hashlib.sha256(data).hexdigest() != expected:
            raise ValueError('Euler import: arithmetic source changed: ' + name)


