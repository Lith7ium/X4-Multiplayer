"""Generate src/extension/x4_lan_lab/libraries/factions.xml: the player-faction pool.

x4lan_player1 .. x4lan_player16, one per human slot (p1 -> 1, p2 -> 2, ...). Each machine
shows its own human as the real `player` faction and every other human as that human's pool
faction (ui/player_factions_core.lua). Pool factions are inactive and unknown until the mod
assigns them; they carry no `economic` tag and no faction-logic manager. Like `player` they
carry `claimspace police` (sector claiming; police faction = itself).
Run: python tools/dev/build_player_factions.py
"""
from pathlib import Path

POOL = 16
# Fixed, distinct colours (colour cannot be changed at runtime). No greens (the player's own colour,
# faction_player / text_player), no azure (friendly/neutral relation colour) and no reds (enemy/hostile),
# so a pool faction never reads as "own" or as a relation tier when the UI uses faction colours.
COLOURS = [
    (255, 140, 0), (230, 60, 200), (255, 220, 40), (150, 90, 255), (255, 160, 200), (200, 140, 60),
    (235, 235, 235), (190, 160, 255), (255, 190, 130), (170, 60, 255), (255, 180, 0), (255, 100, 170),
    (210, 180, 140), (200, 100, 220), (240, 240, 120), (170, 170, 170),
]
# Per-slot icon (libraries/icons.xml, textures from tools/dev/build_player_faction_icons.py): a disc in
# the slot colour with the slot number. Never faction_player, which is the player's own logo.
ICON_DIR = 'extensions\\x4_lan_lab\\assets\\textures\\ui\\x4lan'
ICONS = Path(__file__).resolve().parents[2] / 'src/extension/x4_lan_lab/libraries/icons.xml'


def icon_id(index):
    return f'x4lan_player{index}'


def build_icons():
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           '<!-- Generated by tools/dev/build_player_factions.py; do not edit by hand. Player-faction pool icons. -->',
           '<icons>']
    out += [f'  <icon name="{icon_id(i)}" texture="{ICON_DIR}\\{icon_id(i)}.tga" height="256" width="256"></icon>'
            for i in range(1, POOL + 1)]
    out += ['</icons>', '']
    return '\n'.join(out)
# Same basic licences the vanilla player faction starts with (base-game issuers only).
ISSUERS = 'alliance antigone argon buccaneers hatikvah holyorder ministry paranid scaleplate teladi trinity'
ALLIED = '0.75'   # ally range is 0.5..1.0; 1.0 would read as "self" in the UI.
# Base-game factions with <relations locked="1"> and their vanilla relation to "player". Runtime
# set_faction_relation has no effect on them (native probe 20261026, xenon stayed 0), so the pool
# inherits the player's locked relations here, on both sides. Unlocked factions are mirrored at
# runtime (md/x4lan_player_factions.xml RelationMirror).
LOCKED = [('buccaneers', '-0.032'), ('criminal', '-0.5'), ('holyorderfanatic', '-1'), ('khaak', '-1'),
          ('outlaw', '-0.32'), ('scaleplate', '-0.0032'), ('xenon', '-1')]
TARGET = Path(__file__).resolve().parents[2] / 'src/extension/x4_lan_lab/libraries/factions.xml'


def faction_id(index):
    return f'x4lan_player{index}'


def build():
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           '<!-- Generated by dev/build_player_factions.py; do not edit by hand. X4 LAN Lab player-faction pool. -->',
           '<diff>']
    out.append('  <add sel="/factions/faction[@id=\'player\']/relations">')
    out += [f'    <relation faction="{faction_id(i)}" relation="{ALLIED}" />' for i in range(1, POOL + 1)]
    out.append('  </add>')
    for other, value in LOCKED:
        out.append(f'  <add sel="/factions/faction[@id=\'{other}\']/relations">')
        out += [f'    <relation faction="{faction_id(i)}" relation="{value}" />' for i in range(1, POOL + 1)]
        out.append('  </add>')
    out.append('  <add sel="/factions">')
    for i in range(1, POOL + 1):
        r, g, b = COLOURS[i - 1]
        fid = faction_id(i)
        out += [
            f'    <faction id="{fid}" name="LAN Player {i}" description="Human player slot {i} (X4 LAN Lab)." '
            f'shortname="LP{i}" prefixname="LAN Player {i}" behaviourset="default" tags="claimspace police" '
            f'policefaction="{fid}" active="0" known="0">',
            f'      <color r="{r}" g="{g}" b="{b}" />',
            f'      <icon active="{icon_id(i)}" inactive="{icon_id(i)}" />',
            '      <licences>',
            '        <licence type="generaluseship" name="{1001,61}" tags="basic hidden" />',
            f'        <licence type="generaluseequipment" factions="{ISSUERS}" />',
            f'        <licence type="generaluseship" factions="{ISSUERS}" />',
            f'        <licence type="station_gen_basic" factions="{ISSUERS}" />',
            '      </licences>',
            '      <relations>',
            f'        <relation faction="player" relation="{ALLIED}" />',
        ]
        out += [f'        <relation faction="{faction_id(j)}" relation="{ALLIED}" />' for j in range(1, POOL + 1) if j != i]
        out += [f'        <relation faction="{other}" relation="{value}" />' for other, value in LOCKED]
        out += ['      </relations>', '    </faction>']
    out += ['  </add>', '</diff>', '']
    return '\n'.join(out)


if __name__ == '__main__':
    TARGET.parent.mkdir(exist_ok=True)
    TARGET.write_text(build(), encoding='utf-8', newline='\n')
    ICONS.write_text(build_icons(), encoding='utf-8', newline='\n')
    print('wrote', TARGET, ICONS)
