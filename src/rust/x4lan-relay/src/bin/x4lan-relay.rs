//! Drop-in for `python -m x4lan.host`: same options, session selection and console
//! output. (The packaged launchers run the relay in-process through x4lan.monitor;
//! `--bind 0.0.0.0 --session session.json --trading` selects the same session class.)

use std::process::ExitCode;
use std::time::{Duration, Instant};

use x4lan_relay::json::Json;
use x4lan_relay::relay::Relay;
use x4lan_relay::session::{LeaseSource, Level, Session};

const USAGE: &str = "usage: x4lan-relay [-h] [--bind BIND] [--port PORT] [--token TOKEN] [--build BUILD]\n                   [--bubble BUBBLE] [--session SESSION] [--bubble-actions] [--trading]";
const HELP: &str = "Two-slot UDP relay (Rust port of x4lan.host).

options:
  -h, --help         show this help message and exit
  --bind BIND
  --port PORT
  --token TOKEN
  --build BUILD      identical build label on both clients
  --bubble BUBBLE
  --session SESSION  session.json generated by prepare.py
  --bubble-actions
  --trading";

#[derive(Default)]
struct Args {
    bind: Option<String>,
    port: Option<i64>,
    token: Option<String>,
    build: Option<String>,
    bubble: Option<String>,
    session: Option<String>,
    bubble_actions: bool,
    trading: bool,
}

/// argparse's failure: usage plus message on stderr, exit status 2.
fn fail(message: &str) -> ExitCode {
    eprintln!("{USAGE}\nx4lan-relay: error: {message}");
    ExitCode::from(2)
}

const OPTIONS: [(&str, bool); 8] = [
    ("--bind", true),
    ("--port", true),
    ("--token", true),
    ("--build", true),
    ("--bubble", true),
    ("--session", true),
    ("--bubble-actions", false),
    ("--trading", false),
];

/// argparse semantics: `--opt value`, `--opt=value`, unique prefix abbreviations.
fn parse(argv: Vec<String>) -> Result<Option<Args>, String> {
    let mut args = Args::default();
    let mut i = 0;
    while i < argv.len() {
        let arg = &argv[i];
        if arg == "-h" || arg == "--help" {
            return Ok(None);
        }
        let (name, inline) = match arg.split_once('=') {
            Some((n, v)) if n.starts_with("--") => (n, Some(v.to_string())),
            _ => (arg.as_str(), None),
        };
        if !name.starts_with("--") {
            return Err(format!("unrecognized arguments: {arg}"));
        }
        let exact = OPTIONS.iter().find(|(o, _)| *o == name);
        let matches: Vec<_> = OPTIONS.iter().filter(|(o, _)| o.starts_with(name)).collect();
        let (option, takes_value) = match (exact, matches.as_slice()) {
            (Some(o), _) => *o,
            (None, [one]) => **one,
            (None, []) => return Err(format!("unrecognized arguments: {arg}")),
            (None, many) => {
                let names: Vec<&str> = many.iter().map(|(o, _)| *o).collect();
                return Err(format!("ambiguous option: {name} could match {}", names.join(", ")));
            }
        };
        let value = if takes_value {
            match inline {
                Some(v) => Some(v),
                None => {
                    i += 1;
                    match argv.get(i) {
                        Some(v) if !v.starts_with("--") => Some(v.clone()),
                        _ => return Err(format!("argument {option}: expected one argument")),
                    }
                }
            }
        } else if inline.is_some() {
            return Err(format!("argument {option}: ignored explicit argument '{}'", inline.unwrap_or_default()));
        } else {
            None
        };
        match option {
            "--bind" => args.bind = value,
            "--port" => {
                let text = value.unwrap_or_default();
                let port =
                    text.trim().parse::<i64>().map_err(|_| format!("argument --port: invalid int value: '{text}'"))?;
                args.port = Some(port);
            }
            "--token" => args.token = value,
            "--build" => args.build = value,
            "--bubble" => args.bubble = value,
            "--session" => args.session = value,
            "--bubble-actions" => args.bubble_actions = true,
            "--trading" => args.trading = true,
            _ => unreachable!(),
        }
        i += 1;
    }
    Ok(Some(args))
}

/// Python `a or b`: an empty string or zero falls through.
fn or_config(arg: Option<String>, config: &Json, key: &str) -> Option<String> {
    arg.filter(|s| !s.is_empty())
        .or_else(|| config.get(key).filter(|v| v.truthy()).and_then(|v| v.as_str()).map(str::to_owned))
}

fn main() -> ExitCode {
    let args = match parse(std::env::args().skip(1).collect()) {
        Ok(Some(args)) => args,
        Ok(None) => {
            println!("{USAGE}\n\n{HELP}");
            return ExitCode::SUCCESS;
        }
        Err(message) => return fail(&message),
    };
    let config = match &args.session {
        Some(path) => match std::fs::read_to_string(path).map_err(|e| e.to_string()).and_then(|t| Json::parse(&t)) {
            Ok(config) => config,
            Err(e) => {
                eprintln!("x4lan-relay: cannot read {path}: {e}");
                return ExitCode::from(1);
            }
        },
        None => Json::Object(vec![]),
    };
    let (Some(token), Some(build)) = (or_config(args.token, &config, "token"), or_config(args.build, &config, "build"))
    else {
        return fail("supply --session or both --token and --build");
    };
    let bubble = or_config(args.bubble, &config, "bubble").unwrap_or_else(|| "bubble-01".into());
    let port = match args.port.filter(|p| *p != 0) {
        Some(p) => p,
        None => config.get("port").and_then(Json::as_f64).map_or(45841, |p| p as i64),
    };
    let Ok(port) = u16::try_from(port) else {
        eprintln!("x4lan-relay: port must be 0-65535");
        return ExitCode::from(1);
    };
    let mut level = if config.get("coop").is_some_and(Json::truthy) {
        Level::Coop
    } else if args.trading {
        Level::Economy
    } else if args.bubble_actions {
        Level::Bubble
    } else {
        Level::Base
    };
    if config.get("world_sync").is_some_and(Json::truthy) {
        level = Level::Universe;
    }
    let session = match Session::new(level, &token, &build, &bubble, LeaseSource::Os) {
        Ok(session) => session,
        Err(message) => {
            eprintln!("ValueError: {message}");
            return ExitCode::from(1);
        }
    };
    let bind = args.bind.unwrap_or_else(|| "127.0.0.1".into());
    let mut relay = match Relay::bind(&bind, port, session) {
        Ok(relay) => relay,
        Err(e) => {
            eprintln!("OSError: {e}");
            return ExitCode::from(1);
        }
    };
    println!("X4 LAN transform relay on {bind}:{port}; build={build}; bubble={bubble}");
    if args.bubble_actions || args.trading {
        println!("Experimental host-authoritative test bubble.");
    } else {
        println!("Experiment: client poses only; no shared physics, damage, AI or economy.");
    }
    let start = Instant::now();
    let mut last_status = String::new();
    loop {
        relay.step(start.elapsed().as_secs_f64());
        let status: Vec<String> = relay
            .session
            .core
            .peers
            .iter()
            .map(|(slot, p)| format!("{}@{}:{}", slot.as_str(), p.address.ip(), p.address.port()))
            .collect();
        let status = if status.is_empty() { "waiting".to_string() } else { status.join(", ") };
        if status != last_status {
            println!("{status}");
            last_status = status;
        }
        std::thread::sleep(Duration::from_millis(5));
    }
}
