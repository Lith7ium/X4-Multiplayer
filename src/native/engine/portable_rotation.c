/* Original bounded integer port of tools/dev/portable_rotation_reference.py.
 * No float/double, host libm, dynamic allocation, mutable global or engine code.
 * 40 little-endian unsigned32 limbs =1280 bits. Largest required intermediate:
 * series term * residual^2 <=1152 bits; decimal/RNE scaling <=1000 bits.
 * Checked arithmetic refuses capacity overflow rather than truncating.
 */
#include "portable_rotation.h"
#include <string.h>

#define NL 40u
#define Q 384u
typedef struct { uint32_t v[NL]; unsigned n; } big;
typedef struct { big magnitude; unsigned negative; } signed_big;

/* Generated by our original integer Machin-series oracle, not engine tables. */
static const uint32_t PI2[13] = {
    0x9a74865eu,0xdf2a3367u,0x1c6809bbu,0xa29410f3u,0x76273644u,
    0x04177d4cu,0x14cf98e8u,0x52049c11u,0x01b839a2u,0x898cc517u,
    0x42d18469u,0x921fb544u,0x00000001u
};
void x4rot_half_pi_words(uint32_t out[13]) { memcpy(out, PI2, sizeof PI2); }

static void norm(big *a) { while (a->n && !a->v[a->n-1]) --a->n; }
static void small(big *a, uint64_t value) {
    memset(a,0,sizeof *a); a->v[0]=(uint32_t)value; a->v[1]=(uint32_t)(value>>32);
    a->n=a->v[1]?2u:(a->v[0]?1u:0u);
}
static unsigned bits(const big *a) {
    unsigned count=0; uint32_t last;
    if (!a->n) return 0;
    last=a->v[a->n-1]; while (last) { ++count; last>>=1; }
    return (a->n-1)*32u+count;
}
static int compare(const big *a,const big *b) {
    unsigned i;
    if (a->n!=b->n) return a->n>b->n?1:-1;
    for (i=a->n;i;i--) if (a->v[i-1]!=b->v[i-1]) return a->v[i-1]>b->v[i-1]?1:-1;
    return 0;
}
static int increment(big *a) {
    unsigned i=0;
    while (i<a->n && a->v[i]==UINT32_MAX) { a->v[i]=0; ++i; }
    if (i==NL) return 0;
    if (i==a->n) { a->v[i]=1; ++a->n; } else ++a->v[i];
    return 1;
}
static int sum(const big *a,const big *b,big *out) {
    big r; uint64_t carry=0; unsigned i,n=a->n>b->n?a->n:b->n;
    memset(&r,0,sizeof r);
    for (i=0;i<n;i++) { uint64_t x=carry+(i<a->n?a->v[i]:0u)+(uint64_t)(i<b->n?b->v[i]:0u); r.v[i]=(uint32_t)x; carry=x>>32; }
    r.n=n; if (carry) { if (n==NL) return 0; r.v[r.n++]=(uint32_t)carry; }
    *out=r; return 1;
}
static void difference(const big *a,const big *b,big *out) {
    big r; uint64_t borrow=0; unsigned i;
    memset(&r,0,sizeof r);
    for (i=0;i<a->n;i++) { uint64_t y=(i<b->n?b->v[i]:0u)+borrow; r.v[i]=(uint32_t)((uint64_t)a->v[i]-y); borrow=(uint64_t)a->v[i]<y; }
    r.n=a->n; norm(&r); *out=r;
}
static int shift_left(const big *a,unsigned shift,big *out) {
    big r; unsigned i,word=shift/32u,part=shift%32u;
    memset(&r,0,sizeof r);
    if (!a->n) { *out=r; return 1; }
    if (shift>NL*32u || bits(a)>NL*32u-shift) return 0;
    for (i=0;i<a->n;i++) {
        r.v[i+word]|=a->v[i]<<part;
        if (part && i+word+1<NL) r.v[i+word+1]|=a->v[i]>>(32u-part);
    }
    r.n=(bits(a)+shift+31u)/32u; *out=r; return 1;
}
static void shift_right(const big *a,unsigned shift,big *out) {
    big r; unsigned i,word=shift/32u,part=shift%32u;
    memset(&r,0,sizeof r);
    if (word<a->n) {
        r.n=a->n-word;
        for (i=0;i<r.n;i++) {
            r.v[i]=a->v[i+word]>>part;
            if (part && i+word+1<a->n) r.v[i]|=a->v[i+word+1]<<(32u-part);
        }
        norm(&r);
    }
    *out=r;
}
static unsigned bit_at(const big *a,unsigned bit) { return bit/32u<a->n?(a->v[bit/32u]>>(bit%32u))&1u:0u; }
static unsigned any_below(const big *a,unsigned count) {
    unsigned i,words=count/32u,part=count%32u;
    for (i=0;i<words && i<a->n;i++) if (a->v[i]) return 1;
    return part && words<a->n && (a->v[words]&((UINT32_C(1)<<part)-1u));
}
static int rounded_shift(const big *a,unsigned shift,unsigned sticky,big *out) {
    big r; unsigned up=0;
    if (!shift) { *out=*a; return 1; }
    if (bit_at(a,shift-1u)) up=sticky || any_below(a,shift-1u) || bit_at(a,shift);
    shift_right(a,shift,&r); if (up && !increment(&r)) return 0;
    *out=r; return 1;
}
static int product(const big *a,const big *b,big *out) {
    big r; unsigned i,j;
    memset(&r,0,sizeof r);
    if (!a->n || !b->n) { *out=r; return 1; }
    for (i=0;i<a->n;i++) {
        uint64_t carry=0;
        for (j=0;j<b->n;j++) {
            uint64_t value;
            if (i+j>=NL) return 0;
            value=(uint64_t)a->v[i]*b->v[j]+r.v[i+j]+carry;
            r.v[i+j]=(uint32_t)value; carry=value>>32;
        }
        if (carry) { if (i+j>=NL) return 0; r.v[i+j]=(uint32_t)carry; }
    }
    r.n=a->n+b->n; if (r.n>NL) r.n=NL; norm(&r); *out=r; return 1;
}
static int times_small(big *a,uint32_t multiplier) {
    uint64_t carry=0; unsigned i;
    for (i=0;i<a->n;i++) { uint64_t value=(uint64_t)a->v[i]*multiplier+carry; a->v[i]=(uint32_t)value; carry=value>>32; }
    if (carry) { if (a->n==NL) return 0; a->v[a->n++]=(uint32_t)carry; }
    norm(a); return 1;
}
static uint32_t divide_small(big *a,uint32_t divisor) {
    uint64_t remainder=0; unsigned i;
    for (i=a->n;i;i--) { uint64_t value=(remainder<<32)|a->v[i-1]; a->v[i-1]=(uint32_t)(value/divisor); remainder=value%divisor; }
    norm(a); return (uint32_t)remainder;
}
static int divide(const big *numerator,const big *denominator,big *quotient,big *remainder) {
    big d,r=*numerator,q; int shift;
    if (!denominator->n) return 0;
    small(&q,0); shift=(int)bits(numerator)-(int)bits(denominator);
    if (shift>=0) {
        if (!shift_left(denominator,(unsigned)shift,&d)) return 0;
        q.n=(unsigned)shift/32u+1u;
        for (;shift>=0;--shift) {
            if (compare(&r,&d)>=0) { difference(&r,&d,&r); q.v[(unsigned)shift/32u]|=UINT32_C(1)<<((unsigned)shift%32u); }
            shift_right(&d,1,&d);
        }
        norm(&q);
    }
    *quotient=q; *remainder=r; return 1;
}
static int rounded_divide(const big *a,const big *b,big *out) {
    big q,r,twice; int order;
    if (!divide(a,b,&q,&r) || !shift_left(&r,1,&twice)) return 0;
    order=compare(&twice,b);
    if ((order>0 || (order==0 && (q.v[0]&1u))) && !increment(&q)) return 0;
    *out=q; return 1;
}
static int signed_sum(const signed_big *a,const signed_big *b,signed_big *out) {
    signed_big r; int order;
    if (a->negative==b->negative) { r.negative=a->negative; if (!sum(&a->magnitude,&b->magnitude,&r.magnitude)) return 0; }
    else {
        order=compare(&a->magnitude,&b->magnitude);
        if (order>=0) { difference(&a->magnitude,&b->magnitude,&r.magnitude); r.negative=order?a->negative:0u; }
        else { difference(&b->magnitude,&a->magnitude,&r.magnitude); r.negative=b->negative; }
    }
    *out=r; return 1;
}
static int unpack(uint32_t value,uint32_t *magnitude,int *exponent,unsigned *negative) {
    unsigned e=(value>>23)&255u;
    if (e==255u) return X4ROT_UNSUPPORTED;
    *magnitude=(value&0x7fffffu)|(e?0x800000u:0u); *exponent=e?(int)e-150:-149; *negative=value>>31;
    return X4ROT_OK;
}
static int pack(const big *magnitude,int exponent,unsigned negative,uint32_t *out) {
    big r; int top,quantum,shift; uint32_t word;
    if (!magnitude->n) { *out=negative<<31; return X4ROT_OK; }
    top=(int)bits(magnitude)-1+exponent; quantum=top-23; if (quantum < -149) quantum=-149;
    shift=quantum-exponent;
    if (shift>0) { if (!rounded_shift(magnitude,(unsigned)shift,0,&r)) return X4ROT_CAPACITY; }
    else if (!shift_left(magnitude,(unsigned)-shift,&r)) return X4ROT_CAPACITY;
    if (r.n>1) return X4ROT_CAPACITY;
    word=r.v[0]; if (!word) { *out=negative<<31; return X4ROT_OK; }
    if (word>=0x1000000u) { word>>=1; ++quantum; }
    if (quantum>104) return X4ROT_OVERFLOW;
    if (word<0x800000u) { if (quantum!=-149) return X4ROT_CAPACITY; *out=(negative<<31)|word; }
    else *out=(negative<<31)|((uint32_t)(quantum+150)<<23)|(word-0x800000u);
    return X4ROT_OK;
}
int x4rot_multiply(uint32_t left,uint32_t right,uint32_t *out) {
    uint32_t a,b,result; int ae,be,status; unsigned an,bn; big magnitude;
    if (!out || unpack(left,&a,&ae,&an) || unpack(right,&b,&be,&bn)) return X4ROT_UNSUPPORTED;
    small(&magnitude,(uint64_t)a*b); status=pack(&magnitude,ae+be,an^bn,&result);
    if (!status) *out=result;
    return status;
}
int x4rot_add(uint32_t left,uint32_t right,uint32_t *out) {
    uint32_t a,b,result; int ae,be,e,status; signed_big av,bv,total;
    if (!out || unpack(left,&a,&ae,&av.negative) || unpack(right,&b,&be,&bv.negative)) return X4ROT_UNSUPPORTED;
    e=ae<be?ae:be; small(&av.magnitude,a); small(&bv.magnitude,b);
    if (!shift_left(&av.magnitude,(unsigned)(ae-e),&av.magnitude) || !shift_left(&bv.magnitude,(unsigned)(be-e),&bv.magnitude) || !signed_sum(&av,&bv,&total)) return X4ROT_CAPACITY;
    status=pack(&total.magnitude,e,total.negative,&result); if (!status) *out=result; return status;
}
int x4rot_decimal(const char *text,size_t length,uint32_t *out) {
    big numerator,denominator,shifted,rounded; size_t i=0; unsigned negative=0,digits=0,point=0,fractional=0; int top,quantum,status; uint32_t result;
    if (!text || !out || !length || length>256u) return X4ROT_UNSUPPORTED;
    small(&numerator,0); small(&denominator,1);
    if (text[0]=='-') { negative=1; ++i; }
    for (;i<length;i++) {
        unsigned char c=(unsigned char)text[i];
        if (c=='.' && !point) { point=1; continue; }
        if (c<'0' || c>'9') return X4ROT_UNSUPPORTED;
        ++digits; fractional+=point;
        if (!times_small(&numerator,10)) return X4ROT_CAPACITY;
        small(&shifted,(uint32_t)(c-'0')); if (!sum(&numerator,&shifted,&numerator)) return X4ROT_CAPACITY;
    }
    if (!digits) return X4ROT_UNSUPPORTED;
    if (!numerator.n) { *out=negative<<31; return X4ROT_OK; }
    for (i=0;i<fractional;i++) if (!times_small(&denominator,10)) return X4ROT_CAPACITY;
    top=(int)bits(&numerator)-(int)bits(&denominator);
    if (top>=0) { if (!shift_left(&denominator,(unsigned)top,&shifted)) return X4ROT_CAPACITY; if (compare(&numerator,&shifted)<0) --top; }
    else { if (!shift_left(&numerator,(unsigned)-top,&shifted)) return X4ROT_CAPACITY; if (compare(&shifted,&denominator)<0) --top; }
    quantum=top-23; if (quantum < -149) quantum=-149;
    if (quantum<0) { if (!shift_left(&numerator,(unsigned)-quantum,&numerator)) return X4ROT_CAPACITY; }
    else if (!shift_left(&denominator,(unsigned)quantum,&denominator)) return X4ROT_CAPACITY;
    if (!rounded_divide(&numerator,&denominator,&rounded)) return X4ROT_CAPACITY;
    status=pack(&rounded,quantum,negative,&result); if (!status) *out=result; return status;
}
static int series(const signed_big *first,const big *square,unsigned sine,signed_big *out) {
    signed_big total=*first,term=*first; unsigned index;
    for (index=1;index<128u;index++) {
        big value; uint32_t remainder,divisor=2u*index*(sine?2u*index+1u:2u*index-1u);
        if (!product(&term.magnitude,square,&value)) return X4ROT_CAPACITY;
        remainder=divide_small(&value,divisor);
        if (!rounded_shift(&value,2u*Q,remainder!=0,&term.magnitude)) return X4ROT_CAPACITY;
        if (!term.magnitude.n) { *out=total; return X4ROT_OK; }
        term.negative^=1u; if (!signed_sum(&total,&term,&total)) return X4ROT_CAPACITY;
    }
    return X4ROT_CAPACITY;
}
int x4rot_sincos(uint32_t radians,uint32_t out[2]) {
    uint32_t magnitude,result[2]; unsigned negative,quadrant; int exponent,status; big angle,pi,quotient,multiple,square; signed_big residual,sine,cosine,one;
    if (!out || unpack(radians,&magnitude,&exponent,&negative)) return X4ROT_UNSUPPORTED;
    if (!magnitude) { out[0]=radians; out[1]=0x3f800000u; return X4ROT_OK; }
    small(&angle,magnitude); if (!shift_left(&angle,(unsigned)(exponent+(int)Q),&angle)) return X4ROT_CAPACITY;
    memset(&pi,0,sizeof pi); memcpy(pi.v,PI2,sizeof PI2); pi.n=13;
    if (!rounded_divide(&angle,&pi,&quotient) || !product(&quotient,&pi,&multiple)) return X4ROT_CAPACITY;
    quadrant=quotient.v[0]&3u; residual.negative=negative;
    if (compare(&angle,&multiple)>=0) difference(&angle,&multiple,&residual.magnitude);
    else { difference(&multiple,&angle,&residual.magnitude); residual.negative^=1u; }
    if (!shift_left(&residual.magnitude,1,&multiple) || compare(&multiple,&pi)>0) return X4ROT_CAPACITY;
    if (negative) quadrant=(4u-quadrant)&3u;
    if (!product(&residual.magnitude,&residual.magnitude,&square)) return X4ROT_CAPACITY;
    small(&one.magnitude,1); if (!shift_left(&one.magnitude,Q,&one.magnitude)) return X4ROT_CAPACITY; one.negative=0;
    status=series(&residual,&square,1,&sine); if (status) return status;
    status=series(&one,&square,0,&cosine); if (status) return status;
    if (quadrant&1u) { signed_big temp=sine; sine=cosine; cosine=temp; }
    if (quadrant==2u || quadrant==3u) sine.negative^=1u;
    if (quadrant==1u || quadrant==2u) cosine.negative^=1u;
    status=pack(&sine.magnitude,-(int)Q,sine.negative,&result[0]); if (status) return status;
    status=pack(&cosine.magnitude,-(int)Q,cosine.negative,&result[1]); if (status) return status;
    memcpy(out,result,sizeof result); return X4ROT_OK;
}
int x4rot_basis(const uint32_t radians[3],uint32_t out[9]) {
    uint32_t p[2],y[2],r[2],srsp,crsp,a,b,result[9]; int status;
    if (!radians || !out) return X4ROT_UNSUPPORTED;
    status=x4rot_sincos(radians[0],p); if (status) return status;
    status=x4rot_sincos(radians[1],y); if (status) return status;
    status=x4rot_sincos(radians[2],r); if (status) return status;
#define MUL(a_,b_,out_) do { status=x4rot_multiply((a_),(b_),&(out_)); if (status) return status; } while (0)
#define ADD(a_,b_,out_) do { status=x4rot_add((a_),(b_),&(out_)); if (status) return status; } while (0)
    MUL(r[0],p[0],srsp); MUL(r[1],p[0],crsp);
    MUL(r[1],y[1],a); MUL(srsp,y[0],b); ADD(a,b,result[0]);
    MUL(r[0],p[1],a); result[1]=a^0x80000000u;
    MUL(r[1],y[0],a); MUL(srsp,y[1],b); ADD(a^0x80000000u,b,result[2]);
    MUL(r[0],y[1],a); MUL(crsp,y[0],b); ADD(a,b^0x80000000u,result[3]);
    MUL(r[1],p[1],result[4]);
    MUL(r[0],y[0],a); MUL(crsp,y[1],b); ADD(a^0x80000000u,b^0x80000000u,result[5]);
    MUL(p[1],y[0],result[6]); result[7]=p[0]; MUL(p[1],y[1],result[8]);
#undef MUL
#undef ADD
    memcpy(out,result,sizeof result); return X4ROT_OK;
}
int x4rot_offset(unsigned orientation,const struct x4rot_attribute angles[3],uint32_t out[9]) {
    uint32_t radians[3],degrees; unsigned i; int status;
    if (orientation==X4ROT_ABSENT) return X4ROT_KEEP_NATIVE;
    if (orientation!=X4ROT_EULER || !angles || !out) return X4ROT_UNSUPPORTED;
    for (i=0;i<3;i++) {
        if (angles[i].present>1u || (!angles[i].present && (angles[i].text || angles[i].length))) return X4ROT_UNSUPPORTED;
        degrees=0;
        if (angles[i].present && angles[i].length) { status=x4rot_decimal(angles[i].text,angles[i].length,&degrees); if (status) return status; }
        status=x4rot_multiply(degrees,0x3c8efa35u,&radians[i]); if (status) return status;
    }
    return x4rot_basis(radians,out);
}
